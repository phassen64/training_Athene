# Deklaration der Variablen
var_1 = 4
var_2 = 3.14
var_3 = "123"

# Typbestimmung
print(type(var_1))
print(type(var_2))
print(type(var_3))

# Typumwandlung
print(type(float(var_1)))
print(type(float(var_3)))
print(type(int(var_2)))
print(type(int(var_3)))
print(type(str(var_1)))
print(type(str(var_2)))
